"""Generate ecu/include/ecu/ecu_calib_gen.h from the specs and the thermo map fixture.

    python ecu/tools/gen_calib.py            # (re)write the header
    python ecu/tools/gen_calib.py --check    # exit 1 if the committed header is stale

Inputs: spec/engine.yaml (geometry, firing order, idle/redline, stoich AFR), spec/ecu.yaml
(calibration), spec/mvem.yaml (trigger wheel, injector, wall-film and ETC hardware data, the
calibration-dyno knock limit) and mvem/data/thermo_maps.json (VE and MBT from thermo/ runs).
Output is deterministic text: the committed header must be byte-identical to a fresh run.
All values are MODELLED.
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

import numpy as np  # noqa: E402

from mvem import maps, params  # noqa: E402

OUT = ROOT / "ecu" / "include" / "ecu" / "ecu_calib_gen.h"
SEC_PER_MIN = 60.0


def f(x: float) -> str:
    s = np.format_float_positional(np.float32(x), unique=True, trim="0")   # shortest float32 text
    return s + "f"


def klsa_deg(rpm, p_map, ms):
    k, amb = ms["knock"], ms["ambient"]
    return (float(k["klsa_wot_deg"]) + float(k["klsa_per_unit_vacuum_deg"]) * (1.0 - p_map / float(amb["p"]))
            + float(k["klsa_per_krpm_deg"]) * (rpm - float(k["klsa_rpm_ref"])) / 1000.0)


def spark_table(d, es, ms):
    ig = es["ignition"]
    mbt = maps.mbt_advance_table(d)
    out = np.zeros_like(mbt)
    for i, r in enumerate(d["rpm"]):
        for j, p in enumerate(d["map"]):
            out[i, j] = min(mbt[i, j], klsa_deg(r, p, ms) - float(ig["knock_margin_deg"]))
    return np.clip(out, float(ig["min_advance_deg"]), float(ig["max_advance_deg"]))


def rev_ticks(rpm: float, timer_hz: int) -> int:
    return int(round(timer_hz * SEC_PER_MIN / rpm))


def build() -> str:
    spec = params.engine_spec()
    es = params.ecu_spec()
    ms = params.mvem_spec()
    d = maps.load_maps()
    g = params.geometry()
    hw, dec, inj, ig, kn = es["hardware"], es["decoder"], es["injection"], es["ignition"], es["knock"]
    lc, ww, th, idl, rl, fa = (es["lambda_control"], es["wall_wetting"], es["throttle"], es["idle"],
                               es["rev_limit"], es["faults"])
    tr = es["transient"]
    trg, mi, film, etc = ms["trigger"], ms["injector"], ms["fuel_film"], ms["etc"]
    hz = int(hw["timer_hz"])
    upd = int(hw["angle_units_per_deg"])
    ncyl = int(spec["engine"]["cylinders"])
    assert ncyl <= int(hw["cylinders_max"])
    teeth, miss = int(trg["teeth_total"]), int(trg["teeth_missing"])
    pitch_u = 360 * upd // teeth
    assert pitch_u * teeth == 360 * upd, "angle units must divide the tooth pitch"
    den = int(dec["ratio_den"])
    tdc = [int(round(a * upd)) for a in params.firing_tdc_deg(spec)]
    redline = float(spec["engine"]["redline_rpm"])
    cut = redline + float(rl["cut_above_redline_rpm"])
    hyst = float(rl["hysteresis_rpm"])
    limp = float(fa["limp_rpm"])
    ve = np.asarray(d["ve"])
    spk = spark_table(d, es, ms)

    L = []
    a = L.append
    a("/* GENERATED by ecu/tools/gen_calib.py from spec/engine.yaml, spec/ecu.yaml, spec/mvem.yaml and")
    a(" * mvem/data/thermo_maps.json. DO NOT EDIT: change the specs and regenerate. MODELLED calibration. */")
    a("#ifndef ECU_CALIB_GEN_H")
    a("#define ECU_CALIB_GEN_H")
    a("")
    a("#include <stdint.h>")
    a("")
    a("/* ---- integer configuration (angle scheduler and decoder: fixed point only) ---- */")
    ints = [
        ("ECU_TIMER_HZ", f"{hz}u"),
        ("ECU_ANGLE_U_PER_DEG", f"{upd}"),
        ("ECU_NCYL", f"{ncyl}"),
        ("ECU_TEETH_TOTAL", f"{teeth}"),
        ("ECU_TEETH_MISSING", f"{miss}"),
        ("ECU_TEETH_REAL", f"{teeth - miss}"),
        ("ECU_PITCH_U", f"{pitch_u}"),
        ("ECU_REV_U", f"{360 * upd}"),
        ("ECU_CYCLE_U", f"{720 * upd}"),
        ("ECU_TOOTH0_U", f"{int(round(float(trg['tooth0_angle_deg']) * upd))}"),
        ("ECU_CAM_EDGE_U", f"{int(round(float(trg['cam_edge_deg']) * upd))}"),
        ("ECU_RATIO_DEN", f"{den}u"),
        ("ECU_GAP_RATIO_NUM", f"{int(round(float(dec['gap_ratio']) * den))}u"),
        ("ECU_DROPOUT_RATIO_NUM", f"{int(round(float(dec['dropout_ratio']) * den))}u"),
        ("ECU_NOISE_RATIO_NUM", f"{int(round(float(dec['noise_ratio']) * den))}u"),
        ("ECU_STALL_TICKS", f"{int(round(float(dec['stall_timeout_s']) * hz))}u"),
        ("ECU_REPEAT_GUARD_U", f"{int(dec['repeat_guard_deg']) * upd}u"),
        ("ECU_SYNC_MIN_GOOD", f"{int(dec['sync_min_good_teeth'])}u"),
        ("ECU_PERIOD_HIST", f"{int(dec['period_average_teeth'])}"),
        ("ECU_DWELL_TICKS", f"{int(round(float(ig['dwell_s']) * hz))}u"),
        ("ECU_EOI_U", f"{int(round(float(inj['eoi_deg']) * upd))}"),
        ("ECU_MAX_PW_U", f"{int(round(float(inj['max_duty']) * 720 * upd))}u"),
        ("ECU_KNOCK_THRESHOLD", f"{int(kn['threshold_counts'])}u"),
        ("ECU_KNOCK_STEP_U", f"{int(round(float(kn['retard_step_deg']) * upd))}"),
        ("ECU_KNOCK_MAX_U", f"{int(round(float(kn['max_retard_deg']) * upd))}"),
        ("ECU_KNOCK_RECOVER_U", f"{int(round(float(kn['recover_deg_per_event']) * upd))}"),
        ("ECU_REV_CUT_TICKS", f"{rev_ticks(cut, hz)}u"),
        ("ECU_REV_RESUME_TICKS", f"{rev_ticks(cut - hyst, hz)}u"),
        ("ECU_LIMP_CUT_TICKS", f"{rev_ticks(limp, hz)}u"),
        ("ECU_LIMP_RESUME_TICKS", f"{rev_ticks(limp - hyst, hz)}u"),
        ("ECU_REV_SPARK_CUT", "1" if rl["spark_cut"] else "0"),
        ("ECU_FAULT_DEBOUNCE", f"{int(fa['debounce_samples'])}"),
    ]
    for k, v in ints:
        a(f"#define {k} {v}")
    decl, defs = [], []
    decl.append(f"extern const int32_t ECU_TDC_U[{ncyl}];   /* firing TDC per cylinder [angle units] */")
    defs.append(f"const int32_t ECU_TDC_U[{ncyl}] = {{{', '.join(str(t) for t in tdc)}}};")
    a("")
    a("/* ---- floating-point calibration (slow loops only) ---- */")
    flts = [
        ("ECU_DT_SLOW", 1.0 / float(hw["slow_loop_hz"])),
        ("ECU_TIMER_HZ_F", float(hz)),
        ("ECU_VD_CYL", g.swept_volume),
        ("ECU_R_AIR", float(ms["ambient"]["R_air"])),
        ("ECU_AFR_STOICH", float(spec["combustion"]["afr_stoich"])),
        ("ECU_LAMBDA_TARGET", float(inj["afr_target_lambda"])),
        ("ECU_INJ_FLOW", float(mi["static_flow"])),
        ("ECU_FILM_X", float(film["x"]) * float(ww["x_scale"])),
        ("ECU_FILM_TAU_REF", float(film["tau_ref"]) * float(ww["tau_scale"])),
        ("ECU_FILM_RPM_REF", float(film["rpm_ref"])),
        ("ECU_FILM_TAU_EXP", float(film["tau_rpm_exponent"])),
        ("ECU_EOI_TO_IVC_DEG", float(spec["valves"]["ivc_deg"]) - float(inj["eoi_deg"])),
        ("ECU_ADV_MIN", float(ig["min_advance_deg"])),
        ("ECU_ADV_MAX", float(ig["max_advance_deg"])),
        ("ECU_LAM_KP", float(lc["kp"])),
        ("ECU_LAM_KI", float(lc["ki"])),
        ("ECU_STFT_LIM", float(lc["stft_limit"])),
        ("ECU_LTFT_LIM", float(lc["ltft_limit"])),
        ("ECU_LTFT_RATE", float(lc["ltft_rate"])),
        ("ECU_CL_DELAY", float(lc["enable_delay_s"])),
        ("ECU_CL_MIN_RPM", float(lc["min_rpm"])),
        ("ECU_MAP_PRED_GAIN", float(tr["map_prediction_gain"])),
        ("ECU_MAP_DERIV_TAU", float(tr["map_derivative_tau_s"])),
        ("ECU_CL_FREEZE_DMAP", float(tr["cl_freeze_dmap_pa_per_s"])),
        ("ECU_CL_FREEZE_HOLD", float(tr["cl_freeze_hold_s"])),
        ("ECU_ETC_KP", float(th["kp_v_per_deg"])),
        ("ECU_ETC_KI", float(th["ki_v_per_deg_s"])),
        ("ECU_ETC_KD", float(th["kd_v_s_per_deg"])),
        ("ECU_ETC_ILIM", float(th["integrator_limit_v"])),
        ("ECU_ETC_VMAX", float(th["max_voltage"])),
        ("ECU_ETC_FF_SCALE", float(th["friction_ff_scale"])),
        ("ECU_ETC_FF_DEADBAND", float(th["friction_ff_deadband_deg"])),
        ("ECU_ETC_R_OVER_KT", float(etc["motor_resistance"]) / float(etc["torque_constant"])),
        ("ECU_ETC_SPRING_RATE", float(etc["spring_rate"])),
        ("ECU_ETC_PRELOAD", float(etc["spring_preload"])),
        ("ECU_ETC_COULOMB", float(etc["coulomb_friction"])),
        ("ECU_ETC_LIMP_DEG", float(etc["limp_opening_deg"])),
        ("ECU_THR_MAX_DEG", float(ms["throttle"]["max_opening_deg"])),
        ("ECU_DEG_PER_RAD", 180.0 / math.pi),
        ("ECU_IDLE_RPM", float(spec["engine"]["idle_rpm"])),
        ("ECU_IDLE_PEDAL_MAX", float(idl["pedal_max"])),
        ("ECU_IDLE_RPM_BAND", float(idl["rpm_band"])),
        ("ECU_IDLE_BASE_DEG", float(idl["base_opening_deg"])),
        ("ECU_IDLE_KP", float(idl["kp_deg_per_rpm"])),
        ("ECU_IDLE_KI", float(idl["ki_deg_per_rpm_s"])),
        ("ECU_IDLE_KD", float(idl["kd_deg_s_per_rpm"])),
        ("ECU_IDLE_TRIM_LIM", float(idl["air_trim_limit_deg"])),
        ("ECU_IDLE_SPARK_RESERVE", float(idl["spark_reserve_deg"])),
        ("ECU_IDLE_SPARK_KP", float(idl["spark_kp_deg_per_rpm"])),
        ("ECU_IDLE_SPARK_LIM", float(idl["spark_limit_deg"])),
        ("ECU_MAP_MIN", float(fa["map_min"])),
        ("ECU_MAP_MAX", float(fa["map_max"])),
        ("ECU_TPS_SUM_TOL", float(fa["tps_sum_tolerance_deg"])),
        ("ECU_LAMBDA_MIN", float(fa["lambda_min"])),
        ("ECU_LAMBDA_MAX", float(fa["lambda_max"])),
        ("ECU_TEMP_MIN", float(fa["temp_min"])),
        ("ECU_TEMP_MAX", float(fa["temp_max"])),
        ("ECU_IAT_DEFAULT", float(fa["iat_default"])),
    ]
    for k, v in flts:
        a(f"#define {k} {f(v)}")
    a("")

    def arr1(name, xs):
        a(f"#define {name}_N {len(xs)}")
        decl.append(f"extern const float {name}[{len(xs)}];")
        defs.append(f"const float {name}[{len(xs)}] = {{{', '.join(f(x) for x in xs)}}};")

    def arr2(name, m):
        a(f"#define {name}_NR {m.shape[0]}")
        a(f"#define {name}_NC {m.shape[1]}")
        decl.append(f"extern const float {name}[{m.shape[0]}][{m.shape[1]}];")
        defs.append(f"const float {name}[{m.shape[0]}][{m.shape[1]}] = {{")
        for row in m:
            defs.append("    {" + ", ".join(f(x) for x in row) + "},")
        defs.append("};")

    arr1("ECU_DEAD_VBATT", mi["deadtime_vbatt"])
    arr1("ECU_DEAD_S", mi["deadtime_s"])
    arr1("ECU_PEDAL_X", th["pedal_points"])
    arr1("ECU_PEDAL_DEG", th["opening_deg"])
    arr1("ECU_LIMP_OPEN_X", fa["limp_map_opening_deg"])
    arr1("ECU_LIMP_MAP_PA", fa["limp_map_pa"])
    arr1("ECU_TAB_RPM", d["rpm"])
    arr1("ECU_TAB_MAP", d["map"])
    arr2("ECU_VE_TABLE", ve)
    arr2("ECU_SPARK_TABLE", spk)
    a("")
    a("/* speed-density and spark tables: rows = rpm axis, columns = MAP axis [Pa].")
    a(" * ECU_VE_TABLE: volumetric efficiency from thermo/ two-zone runs (mvem/maps.py).")
    a(" * ECU_SPARK_TABLE: base spark [deg BTDC] = min(MBT from thermo, calibration knock limit - margin). */")
    L.extend(decl)
    a("")
    a("#ifdef ECU_CALIB_DEFINE_TABLES   /* defined in exactly one translation unit (src/calib.c) */")
    L.extend(defs)
    a("#endif")
    a("")
    a("#endif")
    return "\n".join(L) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="generate the ECU calibration header")
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--out", default=str(OUT))
    a = ap.parse_args(argv)
    txt = build()
    out = Path(a.out)
    if a.check:
        ok = out.exists() and out.read_text() == txt
        print("calibration header up to date" if ok else f"STALE: {out}")
        return 0 if ok else 1
    out.write_text(txt)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
