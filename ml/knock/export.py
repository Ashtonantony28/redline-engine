"""Generate ecu/targets/rv64/gen/knock_weights.h from ml/policies/knock_int8.json
(`python -m ml.knock.export`, run by the RV64 Makefile when the policy changes)."""
from __future__ import annotations

import sys

from ml.knock import golden
from redline.spec import ROOT

OUT = ROOT / "ecu" / "targets" / "rv64" / "gen" / "knock_weights.h"
LANES = 8
PER_LINE = 16


def _arr(ctype, name, vals, align=False):
    body = ",\n    ".join(", ".join(str(int(v)) for v in vals[i:i + PER_LINE]) for i in range(0, len(vals), PER_LINE))
    al = f"_Alignas({LANES}) " if align else ""
    return f"static const {al}{ctype} {name}[{len(vals)}] = {{\n    {body}\n}};\n"


def render(policy: dict) -> str:
    layers = policy["layers"]
    n_in = len(layers[0]["W_q"][0])
    hidden = [len(L["W_q"]) for L in layers[:-1]]
    if n_in % LANES or any(h % LANES for h in hidden) or len(layers[-1]["W_q"]) != 1:
        raise ValueError("layer widths must be multiples of 8 and the output a single unit")
    o = ["/* GENERATED by ml/knock/export.py from ml/policies/knock_int8.json. DO NOT EDIT.",
         " * int8 knock-detector MLP for the Xmlacc kernel (knock_kernel.c). MODELLED training data. */",
         "#ifndef KNOCK_WEIGHTS_H", "#define KNOCK_WEIGHTS_H", "", "#include <stdint.h>", "",
         f"#define KNOCK_N_IN {n_in}u", f"#define KNOCK_N_LAYERS {len(layers)}u",
         f"#define KNOCK_MAX_HIDDEN {max(hidden)}u", f"#define KNOCK_THRESHOLD_Q {int(policy['threshold_q'])}",
         f"#define KNOCK_LOGIT_SCALE {float(policy['logit_scale']):.9e}f", "",
         "typedef struct {", "    const int8_t *w;      /* n_out rows of in_words * 8 int8, row major */",
         "    const int32_t *b;", "    const int32_t *m;     /* 0 for the output layer */",
         "    const uint8_t *s;", "    uint32_t n_out;", "    uint32_t in_words;", "} knock_layer_t;", "",
         "extern const knock_layer_t KNOCK_LAYERS[KNOCK_N_LAYERS];", "", "#ifdef KNOCK_DEFINE_TABLES"]
    rows = []
    for i, L in enumerate(layers):
        o.append(_arr("int8_t", f"KNOCK_W{i}", [v for row in L["W_q"] for v in row], align=True))
        o.append(_arr("int32_t", f"KNOCK_B{i}", L["b_q"]))
        if "M" in L:
            o.append(_arr("int32_t", f"KNOCK_M{i}", L["M"]))
            o.append(_arr("uint8_t", f"KNOCK_S{i}", L["S"]))
            m, s = f"KNOCK_M{i}", f"KNOCK_S{i}"
        else:
            m, s = "0", "0"
        rows.append(f"    {{KNOCK_W{i}, KNOCK_B{i}, {m}, {s}, {len(L['W_q'])}u, {len(L['W_q'][0]) // LANES}u}}")
    o.append("const knock_layer_t KNOCK_LAYERS[KNOCK_N_LAYERS] = {\n" + ",\n".join(rows) + "\n};")
    o += ["#endif", "", "#endif", ""]
    return "\n".join(o)


def main(argv=None) -> int:
    text = render(golden.load_policy())
    if argv and "--check" in argv:
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale: run python -m ml.knock.export", file=sys.stderr)
            return 1
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
